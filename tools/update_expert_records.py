def add_training_record(file_path, records):
    """向专家档案添加实战训练记录"""

    if not os.path.exists(file_path):
        print(f"文件不存在: {file_path}")
        return

    with open(file_path, 'r', encoding='utf-8') as f:
        content = f.read()

    # 检查是否已有"实战训练记录"章节
    if "## 实战训练记录" in content:
        # 找到"实战训练记录"章节的位置
        section_start = content.find("## 实战训练记录")
        # 找到下一个 ## 章节标题
        next_section = content.find("\n## ", section_start + 1)
        if next_section == -1:
            # 如果没有下一个章节，找到文件末尾
            next_section = len(content)

        existing_records = content[section_start:next_section]
    else:
        existing_records = ""
        section_start = len(content)

    # 生成新的训练记录
    new_records = "\n\n> 以下内容来自2026-05-26的圆桌讨论训练。\n"

    for date, topic, points, new_views in records:
        new_records += f"\n### {date} 话题：{topic}\n\n"
        new_records += "**实战发言要点**：\n"
        for point in points:
            new_records += f"- {point}\n"
        new_records += "\n**新增视角**：\n"
        for view in new_views:
            new_records += f"- {view}\n"
        new_records += "\n---\n"

    # 如果已有章节，更新内容
    if existing_records:
        content = content[:section_start] + "## 实战训练记录（V6.0）" + new_records + content[next_section:]
    else:
        content += "\n\n---\n\n## 实战训练记录（V6.0）" + new_records

    with open(file_path, 'w', encoding='utf-8') as f:
        f.write(content)

    print(f"已更新: {file_path}")


def main():
    base_path = "d:/vibe_coding/zhengliu/expert-library/experts"

    for expert_id, records in training_records.items():
        file_path = os.path.join(base_path, expert_id_to_file.get(expert_id, ""))
        if file_path and os.path.exists(file_path):
            add_training_record(file_path, records)
        else:
            print(f"文件不存在: {file_path}")

    print("\n所有专家档案更新完成！")


if __name__ == "__main__":
    main()
